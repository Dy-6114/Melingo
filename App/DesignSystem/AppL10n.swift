import Foundation
import Domain

/// Lightweight UI strings keyed by `UserProfile.uiLocale` (native / explanation language).
/// Falls back to English. Auto-synced from the user's native language when unset.
enum AppL10n {
    /// Locale code read from UI; mutated only via `sync(from:)` on the main actor.
    nonisolated(unsafe) private(set) static var code: String = Self.detectSystemCode()

    static func sync(from profile: UserProfile) {
        let preferred = profile.uiLocale.trimmingCharacters(in: .whitespacesAndNewlines)
        if !preferred.isEmpty, preferred != "auto" {
            code = normalize(preferred)
            return
        }
        // Prefer explanation / native language, then system locale.
        let native = profile.preferredLanguagePair.target
        code = normalize(native.isEmpty ? detectSystemCode() : native)
    }

    /// Live UI locale during onboarding / Settings before profile is saved.
    static func setCode(_ raw: String) {
        code = normalize(raw)
    }

    /// Default uiLocale for a new profile: follow the system language when supported.
    static func defaultUILocale() -> String {
        detectSystemCode()
    }

    static func t(_ key: String) -> String {
        table[code]?[key] ?? table["en"]?[key] ?? key
    }

    /// Soft daily reminder lines in the user's UI / native language.
    static let softReminderCount = 15

    /// Picks a calm line; `dayOffset` rotates the pool across scheduled days.
    static func softReminderBody(dayOffset: Int = 0) -> String {
        let dayOfYear = Calendar.current.ordinality(of: .day, in: .year, for: Date()) ?? 1
        let idx = ((dayOfYear + dayOffset - 1) % softReminderCount) + 1
        let key = String(format: "review.reminder.soft.%02d", idx)
        return t(key)
    }

    private static func detectSystemCode() -> String {
        let preferred = Locale.preferredLanguages.first ?? Locale.current.identifier
        return normalize(preferred)
    }

    private static func normalize(_ raw: String) -> String {
        let base = raw.split(separator: "-").first.map(String.init)?.lowercased() ?? "en"
        switch base {
        case "zh", "cn", "zh_hans", "zh_hant": return "zh"
        case "jp": return "ja"
        case "en", "ja", "ko", "ru", "es", "fr", "de", "it", "pt", "vi", "th":
            return base
        default:
            return table[base] != nil ? base : "en"
        }
    }

